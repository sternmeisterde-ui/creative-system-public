/** Полный блок для сценариев и брифов (~500 токенов). */
export const SPEECH_RULES_BLOCK = `
ПРАВИЛА ЖИВОЙ РЕЧИ (из корпуса 5000 сильных русскоязычных рилсов; цифры — факты корпуса):
- Пиши как говорят, не как пишут. Медиана реплики 6 слов, половина реплик короче 6 слов, длиннее 20 слов — только 5%. Чередуй реплики по 2–5 слов с одной длинной на 15–20.
- Каждая пятая реплика начинается с «и», «а», «ну», «вот», «да». В речи это норма.
- 2–3 заполнителя на 100 слов в местах смены мысли: «ну», «вот», «короче», «слушай», «честно», «на самом деле», «по факту». Ноль заполнителей = читка, больше 6 = каша.
- Говорящий присутствует как «я» (3 «я/мне/меня» на 100 слов). Адресат один на ролик: «ты» для охвата и UGC, «вы» для экспертного тона. Без адресата нельзя.
- Конструкции устности: «у меня / у тебя / у нас есть» (не «иметь»), «потому что» (не «поскольку»), «то есть», «что-то / какой-то» для неважных деталей, «вот так вот», «мы с тобой».
- Один–два вопроса на ролик, не два подряд. Один контраст («раньше / сейчас», «а это / а вот это»). Один повтор слова или фразы ради эмоции («да да да», «давай давай»).
- Историю рассказывай в настоящем времени и через деталь, а не оценку: не «было страшно», а «руки трясутся, когда набираю номер».
- Хук ≤ 12 слов. Лучшие типы: я-история с конкретикой («Я три года мыла полы с дипломом экономиста»), провокация-утверждение точкой, ты-ситуация («Если у тебя диплом лежит в шкафу…»), обещание результата («Сейчас покажу…»). Запрещено: «Всем привет, меня зовут», «в этом видео я расскажу», новостная цифра-факт, абстрактный вопрос («как стать счастливым?»).
- Призыв: комментарий («напиши в комментариях, сколько тебе лет»), подписка, директ — или панч без призыва. НЕ «переходи по ссылке», НЕ «сохрани видео»: по вовлечению проигрывают в разы.
- Ноль: причастий и деепричастий («сделав», «являющийся»), «который» дважды подряд, перечислений ровно из трёх, каркаса «не просто X, а Y», риторического вопроса с немедленным ответом в каждой реплике.
- Бан-слова (в живой речи их нет): ${rules.ban_words.slice(0, 22).join(", ")}.
  Замены: однако → но / а; данный → этот; является → это; осуществлять → делать; приобрести → купить; необходимо → надо / нужно; в настоящее время → сейчас; поскольку → потому что; таким образом → так что / короче; в первую очередь → самое главное; значительно → сильно / в разы; действительно → реально / прям; позволяет → можно / даёт; оптимальный / эффективный → нормальный / рабочий.
- Сленг — приправа, не основа: уместны «прям», «реально», «круто», «кайф», «норм», «окей», «блин», «капец», «жесть»; молодёжный сленг («кринж», «краш», «вайб») не форсировать. Мат исключён.
- Немецкие термины произносятся по-русски и в репликах для озвучки пишутся кириллицей с ударением: джобце́нтр (Jobcenter), а́усбильдунг (Ausbildung), у́мшулюнг (Umschulung), би́льдунгсгутшайн (Bildungsgutschein), а́рбайтсамт (Arbeitsamt), терми́н (Termin).
`.trim();

/** Короткий блок для коротких монологов и voice-over (25–35 слов) — совместим с ElevenLabs. */
export const SPEECH_RULES_VOICE_BLOCK = `
- Реплики по 3–8 слов, одна может быть длиннее. Начни одну реплику с «ну», «вот», «короче» или «слушай» — это живая речь, не мусор
- Обращение к зрителю на «ты» (или на «вы», если так в брифе) и хотя бы одно «я / у меня / мне»
- Никаких книжных слов: «является», «данный», «осуществлять», «необходимо», «позволяет», «эффективный», «уникальный», «в современном мире», «важно отметить»; никаких причастий и триад
- Для озвучки ставь знак ударения (буква + U+0301) в трудных словах и заимствованиях: звони́т, догово́р, поняла́, взяла́, началась́→начала́сь, телегра́м, инстагра́м, дире́кт, джобце́нтр, а́усбильдунг; омографы (за́мок/замо́к, го́да/года́) тоже с ударением
- Немецкие термины — кириллицей: джобце́нтр, би́льдунгсгутшайн, а́рбайтсамт
- Финал не «переходи по ссылке» и не «сохрани»: вопрос к зрителю, просьба написать в комментариях или просто панч
`.trim();

export function getSpeechRulesBlock(kind: "full" | "voice" = "full"): string {
  return kind === "voice" ? SPEECH_RULES_VOICE_BLOCK : SPEECH_RULES_BLOCK;
}
